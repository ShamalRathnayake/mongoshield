/**
 * Generates docs/errors.md from the error codes in src/errors.ts, so the
 * documentation can never drift from the code.
 *
 * Run with: pnpm docs:errors   (CI runs it with --check to fail on drift)
 */

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { ERROR_CODES } from "../src/errors.ts";

const outputPath = fileURLToPath(new URL("../../../docs/errors.md", import.meta.url));
const checkOnly = process.argv.includes("--check");

/** Builds the Markdown page: an intro, a summary table, then one anchor per code. */
function render(): string {
  const lines: string[] = [
    "# Error codes",
    "",
    "<!-- Generated by packages/mongoshield/scripts/generate-error-docs.ts. Do not edit by hand. -->",
    "",
    "Every MongoShield failure is a `MongoShieldError` with a stable `code`. The CLI exits with",
    "the code's exit status, so scripts can react to specific failures.",
    "",
    "```ts",
    'import { isMongoShieldError } from "mongoshield";',
    "",
    "try {",
    "  await shield.backup();",
    "} catch (error) {",
    '  if (isMongoShieldError(error, "MS_STORAGE_FORBIDDEN")) {',
    "    // fix credentials",
    "  }",
    "}",
    "```",
    "",
    "| Code | Exit | Meaning |",
    "|---|---|---|",
  ];

  for (const [code, info] of Object.entries(ERROR_CODES)) {
    lines.push(
      `| [\`${code}\`](#${code.toLowerCase()}) | ${info.exitCode} | ${info.description} |`,
    );
  }
  lines.push("");

  for (const [code, info] of Object.entries(ERROR_CODES)) {
    lines.push(`## ${code.toLowerCase()}`, "", `**\`${code}\`** · exit code ${info.exitCode}`, "");
    lines.push(info.description, "");
  }
  return lines.join("\n");
}

const rendered = render();

if (checkOnly) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== rendered) {
    console.error("docs/errors.md is out of date. Run `pnpm docs:errors`.");
    process.exit(1);
  }
} else {
  await writeFile(outputPath, rendered);
}
