/**
 * Helpers shared by the scripts that generate the website's content.
 *
 * Three scripts run before every `astro dev` / `astro build` (see package.json):
 *
 *   sync-docs.ts            copies docs/guides, docs/specs and docs/errors.md into the site
 *   gen-cli-reference.ts    renders one page per CLI command from the command specs
 *   gen-config-reference.ts renders the config file reference from the zod schema
 *
 * Everything they write is listed in website/.gitignore: the Markdown in docs/ and the
 * TypeScript in packages/ stay the single source of truth.
 */

import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/** The repository root (website/scripts/ → ../..). */
export const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");

/** Where Starlight reads pages from. */
export const CONTENT_DIR = join(REPO_ROOT, "website", "src", "content", "docs");

/** The GitHub repository, used for "edit this page" and links to files outside docs/. */
export const GITHUB_REPO = "https://github.com/ShamalRathnayake/mongoshield";

/** The branch the site is built from. */
export const GITHUB_BRANCH = "main";

/** A link that opens a repository file in GitHub's editor. */
export function githubEditUrl(repoPath: string): string {
  return `${GITHUB_REPO}/edit/${GITHUB_BRANCH}/${repoPath}`;
}

/** A link that shows a repository file (`blob`) or directory (`tree`) on GitHub. */
export function githubViewUrl(repoPath: string, kind: "blob" | "tree" = "blob"): string {
  return `${GITHUB_REPO}/${kind}/${GITHUB_BRANCH}/${repoPath}`;
}

/** Page metadata written as YAML frontmatter. */
export interface Frontmatter {
  readonly title: string;
  readonly description?: string | undefined;
  /** Where "Edit page" points: the real source of a generated page. */
  readonly editUrl?: string | undefined;
  /** Position in an autogenerated sidebar group (lower comes first). */
  readonly sidebarOrder?: number | undefined;
  /** Label in the sidebar, when it should differ from the title. */
  readonly sidebarLabel?: string | undefined;
}

/**
 * Renders frontmatter. Strings are written as JSON strings, which are valid YAML
 * double-quoted scalars, so titles with `:` or `#` need no further escaping.
 */
export function renderFrontmatter(meta: Frontmatter): string {
  const lines = ["---", `title: ${JSON.stringify(meta.title)}`];
  if (meta.description) lines.push(`description: ${JSON.stringify(meta.description)}`);
  if (meta.editUrl) lines.push(`editUrl: ${JSON.stringify(meta.editUrl)}`);
  if (meta.sidebarOrder !== undefined || meta.sidebarLabel !== undefined) {
    lines.push("sidebar:");
    if (meta.sidebarOrder !== undefined) lines.push(`  order: ${meta.sidebarOrder}`);
    if (meta.sidebarLabel !== undefined)
      lines.push(`  label: ${JSON.stringify(meta.sidebarLabel)}`);
  }
  lines.push("---", "");
  return lines.join("\n");
}

/** A comment placed under the frontmatter of every generated page. */
export function generatedNotice(source: string, script: string): string {
  return `<!-- Generated from ${source} by website/scripts/${script}. Edit the source, not this file. -->\n\n`;
}

/** Deletes a generated directory so pages whose source was removed disappear too. */
export function resetDirectory(path: string): void {
  rmSync(path, { recursive: true, force: true });
  mkdirSync(path, { recursive: true });
}

/** Writes a file, creating its directory first. */
export function writePage(path: string, content: string): void {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
}

/**
 * Escapes text for use as Markdown prose (or inside a table cell), leaving
 * `code spans` untouched. Command descriptions contain things like `app.*`,
 * `<path>` and `$gte`, which would otherwise turn into emphasis or HTML.
 */
export function escapeMarkdown(text: string): string {
  // Odd indexes of the split are the contents of `code spans`.
  const pieces = text.split("`");
  return pieces
    .map((piece, index) => {
      if (index % 2 === 1) return `\`${piece}\``;
      return piece.replace(/[\\*_<>[\]|]/g, (character) => `\\${character}`);
    })
    .join("");
}

/**
 * Text for a Markdown table cell. GitHub-flavoured tables split on `|` even inside
 * code spans, so a pipe there must be escaped too.
 */
export function tableCell(text: string): string {
  const pieces = escapeMarkdown(text).split("`");
  return pieces
    .map((piece, index) => (index % 2 === 1 ? piece.replace(/\|/g, "\\|") : piece))
    .join("`");
}

/** A `code span` that is safe in a table cell. */
export function codeCell(text: string): string {
  return `\`${text.replace(/\|/g, "\\|")}\``;
}

/** Joins hard-wrapped lines into paragraphs; blank lines separate paragraphs. */
export function unwrapParagraphs(text: string): string {
  return text
    .split(/\n\s*\n/)
    .map((paragraph) => paragraph.split("\n").join(" ").trim())
    .filter((paragraph) => paragraph.length > 0)
    .join("\n\n");
}
